function normalizeText(value: string): string {
  return value
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .trim();
}

export function findTacoFood(nameOrKey: string): TacoFoodEntry | null {
  const q = normalizeText(nameOrKey);
  if (!q) return null;

  // Exact key or exact name match first
  const exact = TACO_FOODS.find(
    (item) =>
      item.key === q ||
      normalizeText(item.name) === q ||
      item.aliases.some((alias) => normalizeText(alias) === q),
  );
  if (exact) return exact;

  // Partial inclusion match (prefer longer alias match)
  let bestMatch: TacoFoodEntry | null = null;
  let bestScore = 0;
  for (const item of TACO_FOODS) {
    const candidates = [normalizeText(item.name), ...item.aliases.map(normalizeText)];
    for (const c of candidates) {
      if (q.includes(c) || c.includes(q)) {
        const score = Math.min(c.length, q.length);
        if (score > bestScore && score >= 3) {
          bestScore = score;
          bestMatch = item;
        }
      }
    }
  }
  return bestMatch;
}

export function searchTacoFoods(query: string, limit = 8): TacoFoodEntry[] {
  const q = normalizeText(query);
  if (!q) return TACO_FOODS.slice(0, limit);
  return TACO_FOODS.filter(
    (item) =>
      normalizeText(item.name).includes(q) ||
      item.aliases.some((a) => normalizeText(a).includes(q)),
  ).slice(0, limit);
}

/**
 * Deterministic TACO/TBCA nutrition calculator.
 * Never fabricates micronutrients that are null in the Brazilian composition tables.
 */
export function calculateRecipeNutrition(
  ingredients: RecipeIngredient[],
  servings: number,
): { perServing: NutritionBreakdown; matchedCount: number; totalCount: number } {
  const safeServings = Math.max(1, Number(servings) || 1);
  let calories = 0;
  let proteinG = 0;
  let carbsG = 0;
  let fatG = 0;
  let saturatedFatG = 0;
  let hasSatFat = false;
  let fiberG = 0;
  let sugarG = 0;
  let hasSugar = false;
  let sodiumMg = 0;
  let calciumMg = 0;
  let hasCalcium = false;
  let ironMg = 0;
  let hasIron = false;
  let vitaminCMg = 0;
  let hasVitC = false;
  let potassiumMg = 0;
  let hasPotassium = false;

  let matchedCount = 0;
  const sources = new Set<string>();

  for (const ing of ingredients) {
    const food = findTacoFood(ing.name);
    const grams = Math.max(0, Number(ing.gramsEstimate) || 0);
    if (food && grams > 0) {
      matchedCount++;
      sources.add(food.source);
      const factor = grams / 100;
      calories += food.calories * factor;
      proteinG += food.proteinG * factor;
      carbsG += food.carbsG * factor;
      fatG += food.fatG * factor;
      fiberG += food.fiberG * factor;
      sodiumMg += food.sodiumMg * factor;

      if (food.saturatedFatG !== null) {
        saturatedFatG += food.saturatedFatG * factor;
        hasSatFat = true;
      }
      if (food.sugarG !== null) {
        sugarG += food.sugarG * factor;
        hasSugar = true;
      }
      if (food.calciumMg !== null) {
        calciumMg += food.calciumMg * factor;
        hasCalcium = true;
      }
      if (food.ironMg !== null) {
        ironMg += food.ironMg * factor;
        hasIron = true;
      }
      if (food.vitaminCMg !== null) {
        vitaminCMg += food.vitaminCMg * factor;
        hasVitC = true;
      }
      if (food.potassiumMg !== null) {
        potassiumMg += food.potassiumMg * factor;
        hasPotassium = true;
      }
    }
  }

  const totalCount = Math.max(1, ingredients.length);
  const matchedRatio = Number((matchedCount / totalCount).toFixed(2));
  const sourceList = Array.from(sources).join(' + ');

  const perServing: NutritionBreakdown = {
    calories: Math.round(calories / safeServings),
    proteinG: Number((proteinG / safeServings).toFixed(1)),
    carbsG: Number((carbsG / safeServings).toFixed(1)),
    fatG: Number((fatG / safeServings).toFixed(1)),
    saturatedFatG: hasSatFat ? Number((saturatedFatG / safeServings).toFixed(1)) : null,
    fiberG: Number((fiberG / safeServings).toFixed(1)),
    sugarG: hasSugar ? Number((sugarG / safeServings).toFixed(1)) : null,
    sodiumMg: Math.round(sodiumMg / safeServings),
    calciumMg: hasCalcium ? Math.round(calciumMg / safeServings) : null,
    ironMg: hasIron ? Number((ironMg / safeServings).toFixed(1)) : null,
    vitaminCMg: hasVitC ? Number((vitaminCMg / safeServings).toFixed(1)) : null,
    potassiumMg: hasPotassium ? Math.round(potassiumMg / safeServings) : null,
    sourceLabel:
      matchedCount === 0
        ? 'Estimativa nutricional aproximada'
        : matchedCount < ingredients.length
          ? `Base nutricional NUTRIX (parcial — ${matchedCount}/${ingredients.length} ingredientes; demais estimados)`
          : 'Base nutricional NUTRIX (cálculo proporcional por peso)',
    isEstimate: matchedCount < ingredients.length,
    matchedRatio,
  };

  return { perServing, matchedCount, totalCount: ingredients.length };
}
